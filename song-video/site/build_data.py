import json, os, re, urllib.request, urllib.parse

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
CACHE = os.path.join(HERE, ".sefaria-cache.json")
cache = json.load(open(CACHE, encoding="utf-8")) if os.path.exists(CACHE) else {}

CANT = re.compile(r"[֑-ֽ֯]")      # cantillation marks (meteg kept out too)

def fetch(ref):
    if ref in cache:
        return cache[ref]
    u = "https://www.sefaria.org/api/texts/" + urllib.parse.quote(ref.replace(" ", "_")) + "?lang=he&context=0"
    d = json.load(urllib.request.urlopen(u, timeout=30))
    t = d.get("he")
    if isinstance(t, list):
        t = " ".join(x for x in t if isinstance(x, str))
    t = re.sub(r"<[^>]+>", "", t or "")
    t = t.replace("&nbsp;", " ").replace("&thinsp;", " ").replace("׀", " ")
    t = re.sub(r"\{[פס]\}", "", t)
    t = CANT.sub("", t).replace("\u034f", "")
    t = re.sub(r"\s+", " ", t).strip()
    cache[ref] = t
    json.dump(cache, open(CACHE, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    return t

def link(ref):
    base = ref.replace(" on ", "_on_").replace(" ", "_").replace(":", ".")
    base = re.sub(r"\.(\d+)[a-z]?\.\d+$", lambda m: m.group(0), base)
    return "https://www.sefaria.org/" + base + "?lang=he"

