NIQ = re.compile(r"[\u05B0-\u05C7]")
def cut(t, a, b, key):
    """substring of t from phrase a to phrase b, matching ignoring niqqud"""
    idx, plain = [], []
    for i, ch in enumerate(t):
        if not NIQ.match(ch):
            idx.append(i); plain.append(ch)
    plain = "".join(plain)
    pa, pb = NIQ.sub("", a), NIQ.sub("", b)
    i = plain.find(pa)
    j = plain.find(pb, max(i, 0)) if i >= 0 else -1
    if i < 0 or j < 0:
        raise SystemExit("pick failed for %s: %r .. %r\n%s" % (key, a, b, t[:300]))
    end = idx[j + len(pb) - 1] + 1
    while end < len(t) and NIQ.match(t[end]):
        end += 1
    return t[idx[i]:end]

def ref(key, why=None):
    sref, label, kind, pick = R[key]
    t = fetch(sref)
    if pick:
        a, b = pick
        t = cut(t, a, b, key)
    out = {"src": label, "kind": kind, "text": t, "url": link(sref)}
    if why:
        out["why"] = why
    return out

